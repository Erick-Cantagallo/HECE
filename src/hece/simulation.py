# HECE/src/hece/simulation.py
import re
from hece.lawchecks import find_law_violations
from hece.redflags import find_red_flags, law_level_flags
from hece.numerics import find_numeric_inconsistencies, find_scale_mismatch
from typing import List
from hece.core.models.base import Hypothesis, ConstraintContext

class SimulationEngine:
    """
    Deterministic math engine acting as the Final Validator.
    It takes the AI's intelligent estimation and applies strict physics rules.
    """
    
    def __init__(self, speculative: bool = False):
        # Speculative (inventor) mode: new quantities are allowed but cost points, and every
        # hypothesis must carry a falsifiable prediction and a refutation condition.
        self.speculative = speculative
        self.PENALTY_POSTULATE = 0.10
        self.PENALTY_MISSING_TECHNOLOGY = 0.10  # depends on something that does not exist yet
        self.PENALTY_LOGICAL_FLAW = 0.15
        self.PENALTY_UNPROVEN_PREMISE = 0.05
        # An accusation Python could not verify is the model's unproven opinion: it is shown and sends the hypothesis
        # to human review, but it must not move the score (benchmarks/screening.json: it sank 4 of 5 sound ideas).
        self.PENALTY_UNVERIFIED_ACCUSATION = 0.0
        self.PENALTY_RED_FLAG = 0.15
        self.PENALTY_NUMERIC = 0.15
        self.SUBSTANCE_THRESHOLD = 50
        self.MIN_VIABILITY = 0.65

    def calculate_viability(self, hypothesis: Hypothesis) -> float:
        """
        Validates the AI's base feasibility score using deterministic math.
        """
        # Substance Lock Check
        word_count = len(re.findall(r'\b\w+\b', hypothesis.description))
        if word_count < self.SUBSTANCE_THRESHOLD:
            return 0.0

        # Falsifiability Lock (inventor mode): no prediction/refutation, no score.
        if self.speculative and not (hypothesis.prediction.strip() and hypothesis.refutation.strip()):
            return 0.0

        # ABSOLUTE ZERO RULE (The Guillotine):
        # Only VERIFIED violations (law, quote and mechanism checked by Python) trigger this.
        if len(hypothesis.violated_hard_constraints) > 0:
            return 0.0

        # The base score is now dynamically generated by the AI's judgment of the literature
        base_score = hypothesis.feasibility_score
        
        # Apply deterministic penalties for softer flaws found by the Critic
        total_logic_penalty = len(hypothesis.logical_flaws) * self.PENALTY_LOGICAL_FLAW
        total_premise_penalty = len(hypothesis.assumptions) * self.PENALTY_UNPROVEN_PREMISE
        
        total_unverified_penalty = len(hypothesis.unverified_violations) * self.PENALTY_UNVERIFIED_ACCUSATION
        
        total_redflag_penalty = len(hypothesis.red_flags) * self.PENALTY_RED_FLAG
        total_numeric_penalty = len(hypothesis.numeric_flags) * self.PENALTY_NUMERIC
        total_postulate_penalty = len(hypothesis.postulates) * self.PENALTY_POSTULATE if self.speculative else 0.0
        total_postulate_penalty += len(hypothesis.missing_technology) * self.PENALTY_MISSING_TECHNOLOGY
        
        total_penalty = total_logic_penalty + total_premise_penalty + total_unverified_penalty + total_redflag_penalty + total_postulate_penalty + total_numeric_penalty
        
        # Calculate final score, ensuring it doesn't drop below 0.0
        final_score = max(0.0, base_score - total_penalty)
        
        return round(final_score, 2)

    def evaluate(self, hypotheses: List[Hypothesis], boundaries: ConstraintContext) -> List[Hypothesis]:
        """
        Evaluates a batch of hypotheses and updates their status for the Monte Carlo loop.
        """
        evaluated_list = []
        
        for hyp in hypotheses:
            if hyp.ai_estimate is None:
                hyp.ai_estimate = hyp.feasibility_score
            hyp.red_flags = find_red_flags(hyp.description, speculative=self.speculative)
            hyp.numeric_flags = find_numeric_inconsistencies(hyp.description) + find_scale_mismatch(hyp.description)
            self._apply_law_checks(hyp, boundaries)
            score = self.calculate_viability(hyp)
            hyp.feasibility_score = score
            
            # Rejection Sampling conditions (Minimum 65%, 0 broken physics, no law-level red flag)
            if score >= self.MIN_VIABILITY and len(hyp.violated_hard_constraints) == 0 and not law_level_flags(hyp.red_flags):
                hyp.status = "active"
            else:
                hyp.status = "rejected"
            
            # Accepted hypotheses are only screened; red-flagged ones also need a human look.
            if hyp.status == "active" or hyp.red_flags or hyp.numeric_flags or self.is_borderline(hyp):
                hyp.needs_human_review = True
                
            evaluated_list.append(hyp)
            
        return evaluated_list

    @staticmethod
    def _apply_law_checks(hyp: Hypothesis, boundaries: ConstraintContext) -> None:
        """Laws checked by arithmetic (lawchecks.py) become VERIFIED violations, with the calculation as evidence."""
        for law, evidence in find_law_violations(hyp.description):
            key = law.split(" (")[0].split(" in a ")[0]   # 'Second Law of Thermodynamics', 'Speed of light'
            listed = next((c for c in boundaries.hard_constraints if key in c), law)
            if listed not in hyp.violated_hard_constraints:
                hyp.violated_hard_constraints.append(listed)
                hyp.violation_evidence.append(f"[checked by Python] {evidence}")

    def is_borderline(self, hypothesis: Hypothesis) -> bool:
        """Rejected, no verified violation, but within 10 points of the threshold: a human should look."""
        return (hypothesis.status == "rejected" and not hypothesis.violated_hard_constraints
                and round(hypothesis.feasibility_score, 2) >= round(self.MIN_VIABILITY - 0.10, 2))

    def rejection_reason(self, hypothesis: Hypothesis) -> str:
        """Deterministic, human-readable reason why a hypothesis was rejected."""
        words = len(re.findall(r'\b\w+\b', hypothesis.description))
        if words < self.SUBSTANCE_THRESHOLD:
            return f"Substance Lock: description has {words} words (minimum {self.SUBSTANCE_THRESHOLD})."
        if self.speculative and not (hypothesis.prediction.strip() and hypothesis.refutation.strip()):
            return "Falsifiability Lock: the hypothesis has no prediction and/or no refutation condition."
        if hypothesis.violated_hard_constraints:
            ev = " || ".join(hypothesis.violation_evidence)
            return ("Verified violation of: " + "; ".join(hypothesis.violated_hard_constraints) + "."
                    + (f" Evidence: {ev}" if ev else ""))
        blocking = law_level_flags(hypothesis.red_flags)
        if blocking and hypothesis.feasibility_score >= self.MIN_VIABILITY:
            return ("Blocked for human review: the text matches a pattern that contradicts a fundamental law ("
                    + "; ".join(blocking) + "). The score alone would have passed.")
        est = hypothesis.ai_estimate if hypothesis.ai_estimate is not None else hypothesis.feasibility_score
        return (f"AI estimate {est * 100:.0f}% -> final {hypothesis.feasibility_score * 100:.0f}% after penalties "
                f"(logical flaws: {len(hypothesis.logical_flaws)}, assumptions: {len(hypothesis.assumptions)}, "
                f"unverified accusations: {len(hypothesis.unverified_violations)}, red flags: {len(hypothesis.red_flags)}, numeric errors: {len(hypothesis.numeric_flags)}"
                + (f", postulates: {len(hypothesis.postulates)}" if hypothesis.postulates else "")
                + (f", missing technologies: {len(hypothesis.missing_technology)}" if hypothesis.missing_technology else "") + "); "
                f"below the {self.MIN_VIABILITY * 100:.0f}% threshold."
                + (f" {len(hypothesis.unverified_violations)} Critic accusation(s) could not be verified, so the AI estimate "
                   "may reflect unproven claims; human review recommended." if hypothesis.unverified_violations else "")
                + (" Borderline: within 10 points of the threshold; human review recommended." if self.is_borderline(hypothesis) else ""))
